// Apply a recolour, then darken the result one step (DUSK) or two (DUSK2) along BACK.
const DUSK = (m) => { const keys = new Set([...Object.keys(m), ...Object.keys(BACK)]), out = {}; for (const k of keys) { const v = m[k] ?? k; out[k] = BACK[v] ?? v } return out }
const DUSK2 = (m) => { const d = DUSK(m), keys = new Set([...Object.keys(d), ...Object.keys(BACK)]), out = {}; for (const k of keys) { const v = d[k] ?? k; out[k] = BACK[v] ?? v } return out }
